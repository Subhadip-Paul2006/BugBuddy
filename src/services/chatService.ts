/**
 * Creates an initial demonstration session for the chosen language
 * matching the Screen C specification from docs/UI_UX.md.
 */
export function createInitialChatSession(language: CanonicalLanguage = 'cpp'): ChatSession {
  const sample = SAMPLE_SNIPPETS[language] || SAMPLE_SNIPPETS.cpp;

  const initialUserMessage: ChatMessage = {
    id: `msg-${Date.now()}-1`,
    sender: 'user',
    content: `My ${language.toUpperCase()} code crashed unexpectedly:\n\`\`\`${language}\n${sample.code}\n\`\`\`\nError trace:\n${sample.errorTrace}`,
    timestamp: '10:42 AM',
    codeSnippet: sample.code,
    codeLanguage: language,
  };

  const initialAssistantMessage: ChatMessage = {
    id: `msg-${Date.now()}-2`,
    sender: 'assistant',
    content: `"You dereferenced nullptr with astonishing optimism. Did you expect the RAM to invent memory out of pure wishful thinking?"\n\n**Diagnosis:** Evaluated pointer/reference where object address is unmapped. Classic memory fault.\n**Minimal Fix:** Add a guard validation prior to dereferencing or unboxing.`,
    timestamp: '10:42 AM',
    diagnosisResult: {
      id: `${language}-sample-pattern`,
      title: sample.title,
      language,
      category: 'runtime_error',
      difficulty: 'intermediate',
      roast: "You dereferenced nullptr with astonishing optimism. Did you expect the RAM to invent memory out of pure wishful thinking?",
      diagnosis: sample.actualBehavior,
      symptoms: sample.errorTrace,
      debuggingSteps: [
        'Check pointer or reference initialization before invocation.',
        'Validate inputs against null boundary conditions.',
        'Run memory sanitation tests.',
      ],
      buggyCode: sample.code,
      fixedCode: `// Validated Pattern for ${sample.title}\nif (isValid) {\n    // Safe execution path\n}`,
      whyItWorks: sample.expectedBehavior,
      tests: `// Test command for ${language}\npytest -v // or ctest --verbose`,
      sources: [
        {
          title: `${language.toUpperCase()} Language Specification Reference`,
          url: 'https://en.cppreference.com',
        },
      ],
      isDemo: true,
      demoDisclaimer: 'Simulated demonstration session based on pre-canned pattern. Not a live retrieval match.',
      timestamp: new Date().toISOString(),
    },
    suggestedActionChips: ALL_CHIPS,
    isDemo: true,
    demoDisclaimer: 'Simulated demonstration session based on pre-canned pattern.',
  };

  return {
    id: 'session-104',
    title: `Session #104: ${language.toUpperCase()} ${sample.title}`,
    language,
    status: 'Diagnosed',
    messages: [initialUserMessage, initialAssistantMessage],
    createdAt: new Date().toISOString(),
  };
}

/**
 * Generates an assistant response for one of the 7 contextual action chips.
 * All action chip responses are generated by the local demonstration adapter.
 */
export function generateActionResponse(
  action: FollowUpActionType,
  lastDiagnosis: ConfessionResult | undefined,
  language: CanonicalLanguage
): {
  content: string;
  newMood: 'HAPPY' | 'ECSTATIC' | 'DISAPPOINTED' | 'NEUTRAL';
  isDemo: boolean;
  demoDisclaimer: string;
} {
  const bugTitle = lastDiagnosis?.title || `${language.toUpperCase()} Bug`;
  const diagnosisText = lastDiagnosis?.diagnosis || 'Unexpected state evaluation.';
  const fixedCode = lastDiagnosis?.fixedCode || '// Safe pattern example';
  const buggyCode = lastDiagnosis?.buggyCode || '// Erroneous pattern';
  const demoDisclaimer = 'Generated by local demonstration adapter for action chips. Not an external AI model.';

  switch (action) {
    case 'simpler':
      return {
        content: `**Simpler Explanation (Zero Jargon):**\n\nThink of this bug like trying to withdraw gold nuggets from an empty wooden chest without checking if anything is inside first. Your program reached inside with its eyes closed, grabbed thin air, and had a panic attack when it couldn't spend the nonexistent gold!\n\n**Key Takeaway:** Before using any value, check that it actually exists.`,
        newMood: 'HAPPY',
        isDemo: true,
        demoDisclaimer,
      };

    case 'deeper':
      return {
        content: `**Deeper Technical Breakdown (Under The Hood):**\n\n- **Memory Model / Virtual Address Space:** In ${language.toUpperCase()}, accessing unmapped memory (e.g. address \`0x0\`) causes the Memory Management Unit (MMU) to trigger a hardware page fault exception.\n- **Runtime Behavior:** The kernel checks page table permissions, finds no backing physical page, and issues a termination signal (\`SIGSEGV\` / \`NullPointerException\`).\n- **Compiler Optimization Impact:** Compilers often treat undefined behavior as unreachable, allowing aggressive dead-code elimination that removes null checks placed *after* the dereference!\n\nReference: ${lastDiagnosis?.sources?.[0]?.url || 'Language Specification'}`,
        newMood: 'NEUTRAL',
        isDemo: true,
        demoDisclaimer,
      };

    case 'minimal_diff':
      return {
        content: `**Minimal Diff (Tightest 1-3 Line Fix):**\n\nHere is the smallest surgical modification to eliminate the crash without rewriting your architecture:\n\n\`\`\`diff\n- ${buggyCode.split('\n')[0] || 'buggy_invocation();'}\n+ if (target != null) {\n+     ${buggyCode.split('\n')[0] || 'buggy_invocation();'}\n+ }\n\`\`\`\n\nWhy this suffices: Blocks execution path whenever the invalid condition occurs.`,
        newMood: 'HAPPY',
        isDemo: true,
        demoDisclaimer,
      };

    case 'worked_example':
      return {
        content: `**Worked Example (Minimal Reproducible Example):**\n\nHere is a complete, standalone, copy-pasteable solution you can execute immediately:\n\n\`\`\`${language}\n${fixedCode}\n\`\`\`\n\n*Compiled and verified against ${language.toUpperCase()} standard guidelines.*`,
        newMood: 'HAPPY',
        isDemo: true,
        demoDisclaimer,
      };

    case 'more_tests':
      return {
        content: `**More Debugging Tests (3 Edge-Case Assertions):**\n\nAdd these assertions to your test suite to prevent regressions in CI:\n\n\`\`\`${language}\n// Test 1: Boundary condition with null or empty input\nassert(handleInput(null) == defaultValue);\n\n// Test 2: Standard expected behavior\nassert(handleInput(validSample) != null);\n\n// Test 3: Stress test with rapid repeated mutations\nfor (int i = 0; i < 1000; i++) {\n    assert(handleInput(validSample) != null);\n}\n\`\`\`\n\nRun with: \`${lastDiagnosis?.tests || 'npm test'}\``,
        newMood: 'HAPPY',
        isDemo: true,
        demoDisclaimer,
      };

    case 'explain_line':
      return {
        content: `**Line-by-Line Breakdown:**\n\nLooking closely at the failure point in **${bugTitle}**:\n\n1. **Evaluation Order:** The left-hand expression was evaluated first, producing an invalid reference.\n2. **Dereference Trigger:** The dot (\`.\`) or arrow (\`->\`) operator attempted to offset into the memory table.\n3. **Failure State:** Because base address was invalid, offset calculation pointed outside user space memory.\n\n**Fix:** Never chain accessor operators across unchecked nullable expressions.`,
        newMood: 'NEUTRAL',
        isDemo: true,
        demoDisclaimer,
      };

    case 'roast_again':
      return {
        content: `**ByteBuddy's Encore Roast:**\n\n"You came back for *more* pain? Outstanding! Writing bugs this spectacular takes real dedication. If writing memory errors were an Olympic sport, you'd be disqualified for making the judges cry. Go wrap that in a guard condition before your CPU demands hazard pay!"`,
        newMood: 'DISAPPOINTED',
        isDemo: true,
        demoDisclaimer,
      };

    default:
      return {
        content: `I received your action request regarding **${bugTitle}**. Review the diagnosis: ${diagnosisText}`,
        newMood: 'NEUTRAL',
        isDemo: true,
        demoDisclaimer,
      };
  }
}

/**
 * Handles incoming multi-turn chat messages from the developer.
 * Sanitizes secrets, performs Stage 3 retrieval, and returns an assistant response.
 */
export async function sendChatMessage(
  session: ChatSession,
  userInput: string
): Promise<{ userMessage: ChatMessage; assistantMessage: ChatMessage; updatedSession: ChatSession; newMood: 'HAPPY' | 'ECSTATIC' | 'DISAPPOINTED' | 'NEUTRAL' }> {
  const trimmed = userInput ? userInput.trim() : '';
  if (!trimmed) {
    throw new Error('Cannot send empty chat message.');
  }

  // 1. Sanitize user input for secrets (never log secrets!)
  const sanitized = scanAndRedactSecrets(trimmed);

  const now = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

  const userMessage: ChatMessage = {
    id: `msg-${Date.now()}-user`,
    sender: 'user',
    content: sanitized.redactedCode,
    timestamp: now,
  };

  // 2. Perform Knowledge Retrieval
  const retrieval = await searchKnowledge({
    code: sanitized.redactedCode,
    language: session.language,
  });

  let assistantContent = '';
  let diagnosisResult: ConfessionResult | undefined = undefined;
  let newMood: 'HAPPY' | 'ECSTATIC' | 'DISAPPOINTED' | 'NEUTRAL' = 'NEUTRAL';
  let isDemo = false;
  let demoDisclaimer: string | undefined = undefined;

  if (retrieval.result && !retrieval.isNoMatch) {
    diagnosisResult = retrieval.result;
    const modeBadge = diagnosisResult.responseMode === 'RELATED_GUIDANCE'
      ? '**Related Guidance (Pattern Adaptation)**'
      : '**Direct Match (Curated Codex Pattern)**';

    assistantContent = `"${diagnosisResult.roast}"\n\n${modeBadge}\n\n**Diagnosis:** ${diagnosisResult.diagnosis}\n\n**Recommended Fix:**\n\`\`\`${diagnosisResult.language}\n${diagnosisResult.fixedCode}\n\`\`\`\n\n**Why it works:** ${diagnosisResult.whyItWorks}\n\n**Recommended Verification Tests:**\n\`\`\`bash\n${diagnosisResult.tests}\n\`\`\``;
    newMood = 'HAPPY';
    isDemo = diagnosisResult.isDemo ?? false;
    demoDisclaimer = diagnosisResult.demoDisclaimer;
  } else {
    assistantContent = `**No Exact Pattern Match in Curated Knowledge Base**\n\nI inspected your inquiry regarding **${session.language.toUpperCase()}**. While no matching pattern was found in BugBuddy's indexed knowledge base for this exact error, here are common diagnostic checks for ${session.language.toUpperCase()}:\n\n1. Ensure references and pointers are initialized before dereference.\n2. Check boundary conditions on loops and array indexing.\n3. Paste the exact compiler or runtime error trace for higher retrieval precision.`;
    newMood = 'NEUTRAL';
    isDemo = false;
  }

  const assistantMessage: ChatMessage = {
    id: `msg-${Date.now()}-bot`,
    sender: 'assistant',
    content: assistantContent,
    timestamp: now,
    diagnosisResult,
    suggestedActionChips: ALL_CHIPS,
    isDemo,
    demoDisclaimer,
  };

  const updatedSession: ChatSession = {
    ...session,
    status: diagnosisResult ? 'Diagnosed' : 'Debugging',
    messages: [...session.messages, userMessage, assistantMessage],
  };

  return {
    userMessage,
    assistantMessage,
    updatedSession,
    newMood,
  };
}
